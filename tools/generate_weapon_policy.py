"""The JSON policy is the sole source of exact weapon identity and visual profiles."""
import argparse,json
from pathlib import Path
r=Path(__file__).resolve().parents[1]
d=json.loads((r/'mod/effects/weapon_policy.json').read_text())
lines=['// Generated by tools/generate_weapon_policy.py; do not edit.', '#pragma once',f'#define AC_POLICY_VERSION {d["version"]}',f'#define AC_LARGE_RADIUS {d["large_profile"]["radius"]}f',f'#define AC_SMALL_RADIUS {d["small_profile"]["radius"]}f','static int ACWeaponGroup(const char *model) {']
ids=set()
for w in d['weapons']:
 assert w['weapon_id'] not in ids and w['code'] in range(1,6)
 ids.add(w['weapon_id'])
 assert w['entry_wound_material']==('ac/wound_small' if w['code'] in (1,2,5) else 'ac/wound_large')
 assert w['exit_wound_material']==d['small_profile' if w['code']==5 else 'large_profile']['material'] and w['allow_exit_wound'] and w['allow_exit_spray']
 lines.append(f'    if (!Q_stricmp(model,"{w["weapon_id"]}")) return {w["code"]};')
lines+=['    return 0;','}']
text='\n'.join(lines)+'\n';out=r/'code/fgame/ac_weapon_policy.h'
ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args()
if a.check: assert out.read_text()==text,'Regenerate weapon policy'
else: out.write_text(text)
print(f'Validated {len(ids)} exact weapon IDs, policy {d["version"]}')
