"""Generate the engine table from the single campaign manifest."""
import json,sys
from pathlib import Path
r=Path(__file__).resolve().parents[1];data=json.loads((r/'mod/campaign/missions.json').read_text());ops=data['operations']
assert len({o['id'] for o in ops})==len(ops)
inventory={g:[x for x in json.loads((r/'checkpoints/CP06/map-starts.json').read_text())['results'] if x['game']==g] for g in ['AA','SH','BT']}
for g,rows in inventory.items():
    expected={x['map'] for x in rows};actual=[m for o in ops+data['optional'] if o['source_game']==g for m in o['map_chain']]
    assert len(actual)==len(set(actual)) and set(actual)==expected,(g,expected-set(actual))
for i,o in enumerate(ops):
    assert o['next_id']==(ops[i+1]['id'] if i+1<len(ops) else None)
    assert o['gameplay_patch_profile']==('CP00a-BT-v1' if o['source_game']=='BT' else 'WCR-native-drops')
fields=['id','title','date','place','hero','entry','first','last','next','chain','briefing']
lines=['/* Generated by tools/generate_campaign.py; edit mod/campaign/missions.json. */','#ifndef AC_MISSIONS_H','#define AC_MISSIONS_H','typedef struct { int game; '+''.join('const char *'+f+'; ' for f in fields)+'} acMission_t;','static const acMission_t ac_missions[] = {']
for o in ops:
    date=o['game_date_start'] if o['game_date_start']==o['game_date_end'] else o['game_date_start']+' to '+o['game_date_end']
    if o['date_precision']=='historical_context_range':date='1945 (exact game date unspecified)'
    vals=[o['id'],o['display_name'],date,o['location_name'],o['protagonist'],o['entry_map'],o['map_chain'][0],o['map_chain'][-1],o['completion_event']['native_next'],'|'.join(['']+o['map_chain']+o['optional_entry_points']+['']),o['briefing_replay']]
    lines.append('    {'+str(['AA','SH','BT'].index(o['source_game']))+', '+', '.join(json.dumps(v) for v in vals)+'},')
lines+=['};','#define AC_MISSION_COUNT 15','typedef struct { int operation; const char *map; const char *next; const char *title; } acLevel_t;','static const acLevel_t ac_levels[] = {']
for i,o in enumerate(ops):
    for j,m in enumerate(o['map_chain']):
        nxt=o['map_chain'][j+1] if j+1<len(o['map_chain']) else o['completion_event']['native_next']
        lines.append('    {'+str(i)+', '+json.dumps(m)+', '+json.dumps(nxt)+', '+json.dumps(o['level_titles'][m])+'},')
lines+=['};','#define AC_LEVEL_COUNT '+str(sum(len(o['map_chain']) for o in ops)),'#endif']
generated='\n'.join(lines)+'\n'
if '--check' in sys.argv:assert (r/'code/qcommon/ac_missions.h').read_text()==generated,'Campaign header differs from manifest'
else:(r/'code/qcommon/ac_missions.h').write_text(generated)
print('Validated 15 operations, 53 main sections, 1 optional section; generated engine table.')
