"""Generate the shared, fixed loadout catalogue (no game assets)."""
from pathlib import Path
import json
r=Path(__file__).resolve().parents[1]
rows=json.loads((r/'mod/loadout/weapons.json').read_text())
assert len({w['id'] for w in rows})==len(rows)
lines=['// Generated by tools/generate_loadout.py', '#ifndef AC_LOADOUT_H', '#define AC_LOADOUT_H',
 'typedef struct { const char *id, *name, *model; int slot, game, selectable; } acLoadoutWeapon_t;',
 'static const char *ac_loadoutSlots[]={"Sidearm","Rifle","Submachine gun","Machine gun","Grenade","Heavy weapon","Support"};',
 '#define AC_LOADOUT_SLOTS 7', 'static const acLoadoutWeapon_t ac_loadoutWeapons[]={']
for w in rows:
 assert 0<=w['slot']<7 and 0<=w['game']<3
 lines.append('    {%s,%s,%s,%d,%d,%d},'%(json.dumps(w['id']),json.dumps(w['name']),json.dumps(w['model']),w['slot'],w['game'],int(w.get('selectable',True))))
lines+=['};',f'#define AC_LOADOUT_COUNT {len(rows)}','#endif']
(r/'code/qcommon/ac_loadout.h').write_text('\n'.join(lines)+'\n')
print('Loadout catalogue:',len(rows),'weapons')
